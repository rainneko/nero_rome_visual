def arrow(d, p, q):
    d.line([p, q], fill=(255, 230, 60), width=4); a = math.atan2(q[1] - p[1], q[0] - p[0])
    d.polygon([q, (q[0] - 14 * math.cos(a - .45), q[1] - 14 * math.sin(a - .45)), (q[0] - 14 * math.cos(a + .45), q[1] - 14 * math.sin(a + .45))], fill=(255, 230, 60))
for (src, out, title, cap, marks) in S:
    f = os.path.join(SRC, src + '.png')
    if not os.path.exists(f): print('missing', src); continue
    im = Image.open(f).convert('RGB'); W, H = im.size; can = Image.new('RGB', (W, H + 92), (30, 26, 24)); can.paste(im, (0, 0)); d = ImageDraw.Draw(can)
    for (p, q, s) in marks:
        arrow(d, p, q); f2 = F(20, True); b = d.textbbox((0, 0), s, font=f2); w = b[2] - b[0]; x = min(max(p[0] - w / 2, 8), W - w - 8); y = p[1] + (6 if p[1] > q[1] else -32)
        d.rectangle([x - 6, y - 3, x + w + 6, y + 27], fill=(20, 18, 16)); d.text((x, y), s, font=f2, fill=(255, 236, 120))
    d.text((16, H + 10), title, font=F(24, True), fill=(255, 240, 200)); d.text((16, H + 50), cap, font=F(20), fill=(230, 224, 214))
    can.save(os.path.join(OUT, out + '.png')); print('saved', out)
